import ast
from pathlib import Path

from travel_dss.data import ROOT


def link(module,symbol):
    path = ROOT/f'src/travel_dss/{module}.py'
    tree = ast.parse(path.read_text())
    parts = symbol.split('.')
    nodes = tree.body
    node = None
    for part in parts:
        node = next(n for n in nodes if isinstance(n,(ast.FunctionDef,ast.ClassDef)) and n.name == part)
        nodes = getattr(node,'body',[])
    return f'[{module}.{symbol}](../src/travel_dss/{module}.py#L{node.lineno}) (строка {node.lineno})'


