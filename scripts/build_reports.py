manifest = {}
for path in sorted((ROOT/'data').rglob('*')):
    if path.is_file() and path.suffix != '.sqlite':
        manifest[str(path.relative_to(ROOT))] = {'bytes':path.stat().st_size,
            'sha256':hashlib.sha256(path.read_bytes()).hexdigest()}
write_json(ROOT/'reports/data_manifest.json', {'created_at':datetime.now(timezone.utc).isoformat(), 'files':manifest})
